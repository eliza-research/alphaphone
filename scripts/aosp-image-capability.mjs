/**
 * Alpha AOSP image capability declaration (owner decision P-36, issue #420).
 *
 * Phone, Contacts and SMS exist only on the Alpha AOSP image. The app recognises the image by a
 * system feature only the image product declares, together with installation from a system
 * partition (AlphaImageCapability.java). This writes that feature as a product permissions file next
 * to the staged launcher module. It is staging output: only a boot of the built image shows Android
 * reporting the feature to the app.
 */
import fs from "node:fs";
import path from "node:path";

/** Must equal AlphaImageCapability.FEATURE_VERSION. */
export const IMAGE_FEATURE_VERSION = 1;
const pkg = /^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+$/;

export function imageFeatureName(packageName) {
  if (!pkg.test(packageName)) throw new Error(`Invalid package ${packageName}`);
  return `${packageName}.aosp_image`;
}

export function renderImageCapability(packageName) {
  const feature = imageFeatureName(packageName);
  const file = `image-capability/${feature}.xml`;
  return {
    [file]: `<?xml version="1.0" encoding="utf-8"?>
<!-- Alpha AOSP image capability (P-36). Generated by scripts/stage-aosp.mjs. Alpha Phone shows Phone,
     Contacts and SMS only when this feature is present and the app is installed from a system partition. -->
<permissions>
    <feature name="${feature}" version="${IMAGE_FEATURE_VERSION}" />
</permissions>
`,
    productMakefile: `
# Alpha AOSP image capability (scripts/stage-aosp.mjs): the system feature Alpha Phone requires for Phone, Contacts and SMS.
alphaphone_image_capability_dir := $(patsubst %/,%,$(dir $(lastword $(MAKEFILE_LIST))))/image-capability
PRODUCT_COPY_FILES += $(alphaphone_image_capability_dir)/${feature}.xml:$(TARGET_COPY_OUT_PRODUCT)/etc/permissions/${feature}.xml
`,
  };
}

export function writeImageCapability(output, packageName) {
  const files = renderImageCapability(packageName);
  for (const [name, content] of Object.entries(files)) {
    if (name === "productMakefile") continue;
    const file = path.join(output, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, { flag: "wx" });
  }
  fs.appendFileSync(path.join(output, "product.mk"), files.productMakefile);
  return files;
}
